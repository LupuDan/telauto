alter table public.listings drop constraint listings_status_check;
alter table public.listings
  add constraint listings_status_check
  check (status in ('draft', 'active', 'sold', 'hidden', 'rejected'));

create index listings_user_status_idx on public.listings (user_id, status);

-- Same as 0004, but new listings from the website start as "draft".
create or replace function public.before_listing_insert()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  account_created timestamptz;
  max_per_day int;
  recent_count int;
begin
  if public.is_api_request() then
    new.status := 'draft';
    new.views := 0;
    new.created_at := now();
    new.updated_at := now();
    new.expires_at := now() + interval '30 days';
  end if;

  if not public.is_admin() then
    perform pg_advisory_xact_lock(hashtextextended('listing_limit:' || new.user_id::text, 0));

    select created_at into account_created from public.profiles where id = new.user_id;
    max_per_day := case when account_created > now() - interval '7 days' then 3 else 20 end;

    select count(*) into recent_count
    from public.listings
    where user_id = new.user_id and created_at > now() - interval '24 hours';

    if recent_count >= max_per_day then
      raise exception 'LISTING_LIMIT_REACHED'
        using errcode = 'P0001',
              detail = format('max_per_day=%s', max_per_day),
              hint = 'Too many listings in the last 24 hours.';
    end if;
  end if;

  return new;
end;
$$;

-- Minimum photos per category (plan, section 6).
create or replace function public.category_min_photos(p_category_id smallint)
returns int
language sql
stable
set search_path = ''
as $$
  select case c.slug
    when 'telefoane' then 3
    when 'autovehicule' then 5
    else 1
  end
  from public.categories c
  where c.id = p_category_id
$$;

-- Publishes the author's draft after checking photos and (for auto parts) compatibility.
create or replace function public.publish_listing(p_listing_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_listing public.listings%rowtype;
  v_photos int;
  v_min int;
begin
  if not public.is_active_user() then
    raise exception 'NOT_ALLOWED' using errcode = '42501';
  end if;

  select * into v_listing
  from public.listings
  where id = p_listing_id and user_id = auth.uid()
  for update;

  if not found then
    raise exception 'LISTING_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_listing.status <> 'draft' then
    raise exception 'LISTING_NOT_DRAFT' using errcode = 'P0001';
  end if;

  select count(*) into v_photos from public.listing_images where listing_id = p_listing_id;
  v_min := coalesce(public.category_min_photos(v_listing.category_id), 1);
  if v_photos < v_min then
    raise exception 'LISTING_PHOTOS_MISSING'
      using errcode = 'P0001', detail = format('min_photos=%s', v_min);
  end if;

  if (select slug from public.categories where id = v_listing.category_id) = 'piese-auto'
     and not exists (select 1 from public.listing_compatibility where listing_id = p_listing_id) then
    raise exception 'LISTING_COMPATIBILITY_MISSING' using errcode = 'P0001';
  end if;

  update public.listings
  set status = 'active',
      created_at = now(),
      expires_at = now() + interval '30 days'
  where id = p_listing_id;
end;
$$;

revoke execute on function public.publish_listing(uuid) from public, anon;
grant execute on function public.publish_listing(uuid) to authenticated;

---------------------------------------------------------------------------
-- Phone models
---------------------------------------------------------------------------

create table public.phone_models (
  id int generated by default as identity primary key,
  brand_id smallint not null references public.phone_brands (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 60),
  sort_order smallint not null default 100,
  unique (brand_id, name)
);

create index phone_models_brand_idx on public.phone_models (brand_id, sort_order);

alter table public.phone_models enable row level security;

create policy "phone_models: everyone can read"
  on public.phone_models for select to anon, authenticated using (true);
create policy "phone_models: admins can insert"
  on public.phone_models for insert to authenticated with check ((select public.is_admin()));
create policy "phone_models: admins can update"
  on public.phone_models for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "phone_models: admins can delete"
  on public.phone_models for delete to authenticated using ((select public.is_admin()));
