-- New listings: server decides status, views, dates; anti-spam limit.
-- Accounts younger than 7 days: max 3 listings / 24h; older accounts: max 20 / 24h.
-- Not SECURITY DEFINER on purpose: is_api_request() must see the real caller role.
-- The count works under RLS because authors always see all their own listings.
create or replace function public.before_listing_insert()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  account_created timestamptz;
  max_per_day int;
  recent_count int;
begin
  if public.is_api_request() then
    new.status := 'active';
    new.views := 0;
    new.created_at := now();
    new.updated_at := now();
    new.expires_at := now() + interval '30 days';
  end if;

  if not public.is_admin() then
    -- serialize concurrent inserts of the same user so the limit cannot be bypassed
    perform pg_advisory_xact_lock(hashtextextended('listing_limit:' || new.user_id::text, 0));

    select created_at into account_created from public.profiles where id = new.user_id;
    max_per_day := case when account_created > now() - interval '7 days' then 3 else 20 end;

    select count(*) into recent_count
    from public.listings
    where user_id = new.user_id and created_at > now() - interval '24 hours';

    if recent_count >= max_per_day then
      raise exception 'LISTING_LIMIT_REACHED'
        using errcode = 'P0001',
              detail = format('max_per_day=%s', max_per_day),
              hint = 'Too many listings in the last 24 hours.';
    end if;
  end if;

  return new;
end;
$$;

create trigger listings_before_insert
  before insert on public.listings
  for each row execute function public.before_listing_insert();

-- Owners can edit their listing and switch it between "active" and "sold" only.
-- hidden/rejected are moderator decisions; expiry and views change via functions below.
create or replace function public.guard_listing_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if public.is_api_request() and not public.is_admin() then
    new.id := old.id;
    new.user_id := old.user_id;
    new.views := old.views;
    new.created_at := old.created_at;
    new.expires_at := old.expires_at;

    if new.status is distinct from old.status then
      if old.status not in ('active', 'sold') or new.status not in ('active', 'sold') then
        raise exception 'LISTING_STATUS_ADMIN_ONLY' using errcode = '42501';
      end if;
    end if;
  end if;
  return new;
end;
$$;

create trigger listings_guard_update
  before update on public.listings
  for each row execute function public.guard_listing_update();

-- Max 10 photos per listing.
create or replace function public.check_listing_image_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.listing_images where listing_id = new.listing_id) >= 10 then
    raise exception 'LISTING_IMAGE_LIMIT_REACHED' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger listing_images_limit
  before insert on public.listing_images
  for each row execute function public.check_listing_image_limit();

-- "Reactivează" button: owner pushes expiry 30 days from now and sets status back to active.
-- Works for active, sold and expired listings, never for hidden/rejected ones.
create or replace function public.reactivate_listing(p_listing_id uuid)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_expiry timestamptz;
begin
  if not public.is_active_user() then
    raise exception 'NOT_ALLOWED' using errcode = '42501';
  end if;

  update public.listings
  set expires_at = now() + interval '30 days',
      status = 'active'
  where id = p_listing_id
    and user_id = auth.uid()
    and status in ('active', 'sold')
  returning expires_at into new_expiry;

  if new_expiry is null then
    raise exception 'LISTING_NOT_FOUND' using errcode = 'P0002';
  end if;
  return new_expiry;
end;
$$;

-- Counts a view of a visible listing (called from the listing page).
create or replace function public.increment_listing_views(p_listing_id uuid)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.listings
  set views = views + 1
  where id = p_listing_id
    and status = 'active'
    and expires_at > now()
    and user_id is distinct from auth.uid();
$$;

revoke execute on function public.reactivate_listing(uuid) from public, anon;
grant execute on function public.reactivate_listing(uuid) to authenticated;
grant execute on function public.increment_listing_views(uuid) to anon, authenticated;

