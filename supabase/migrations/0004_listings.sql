-- Everyone: active, not expired listings of users who are not blocked.
-- Author: all own listings. Admin: everything.
create policy "listings: read visible, own or as admin"
  on public.listings for select to anon, authenticated
  using (
    (
      status = 'active'
      and expires_at > now()
      and exists (select 1 from public.profiles p where p.id = listings.user_id and not p.is_blocked)
    )
    or user_id = (select auth.uid())
    or (select public.is_admin())
  );

create policy "listings: active users create their own"
  on public.listings for insert to authenticated
  with check (user_id = (select auth.uid()) and (select public.is_active_user()));

create policy "listings: owner (not blocked) or admin can update"
  on public.listings for update to authenticated
  using ((user_id = (select auth.uid()) and (select public.is_active_user())) or (select public.is_admin()))
  with check ((user_id = (select auth.uid()) and (select public.is_active_user())) or (select public.is_admin()));

create policy "listings: owner or admin can delete"
  on public.listings for delete to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

