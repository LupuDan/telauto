-- 0004: listings, private listing data (IMEI/VIN), images, auto-part compatibility.

create table public.listings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  category_id smallint not null references public.categories (id),
  title text not null check (char_length(title) between 3 and 100),
  description text not null default '' check (char_length(description) <= 5000),
  price numeric(12, 2) not null check (price > 0),
  currency text not null default 'MDL' check (currency in ('MDL', 'EUR')),
  negotiable boolean not null default false,
  locality_id smallint not null references public.localities (id),
  condition text not null check (condition in ('new', 'used')),
  -- category-specific fields, see src/lib/categories.ts
  attributes jsonb not null default '{}'::jsonb check (jsonb_typeof(attributes) = 'object'),
  status text not null default 'active' check (status in ('active', 'sold', 'hidden', 'rejected')),
  views int not null default 0 check (views >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 days'),
  -- 'simple' + unaccent works the same for Romanian and Russian text; title weighs more.
  search_vector tsvector generated always as (
    setweight(to_tsvector('simple'::regconfig, public.immutable_unaccent(lower(coalesce(title, '')))), 'A')
    || setweight(to_tsvector('simple'::regconfig, public.immutable_unaccent(lower(coalesce(description, '')))), 'B')
  ) stored
);

create index listings_search_idx on public.listings using gin (search_vector);
create index listings_attributes_idx on public.listings using gin (attributes jsonb_path_ops);
create index listings_category_status_created_idx on public.listings (category_id, status, created_at desc);
create index listings_status_created_idx on public.listings (status, created_at desc);
create index listings_user_idx on public.listings (user_id, created_at desc);
create index listings_locality_idx on public.listings (locality_id);

create trigger listings_set_updated_at
  before update on public.listings
  for each row execute function public.set_updated_at();

-- IMEI (phones) / VIN (vehicles). Separate table because RLS works per row, not per column:
-- visitors must never receive these values (read via get_listing_contact()).
create table public.listing_private (
  listing_id uuid primary key references public.listings (id) on delete cascade,
  imei text check (imei is null or public.is_valid_imei(imei)),
  vin text check (vin is null or public.is_valid_vin(vin))
);

create table public.listing_images (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings (id) on delete cascade,
  -- path inside the "listing-images" bucket: <user_id>/<listing_id>/<file>
  storage_path text not null unique,
  -- 0 = main photo
  position smallint not null check (position between 0 and 9),
  created_at timestamptz not null default now(),
  -- deferrable so the website can swap positions when photos are reordered
  constraint listing_images_position_unique unique (listing_id, position) deferrable initially deferred
);

create index listing_images_listing_idx on public.listing_images (listing_id, position);

create table public.listing_compatibility (
  id bigint generated by default as identity primary key,
  listing_id uuid not null references public.listings (id) on delete cascade,
  make_id int not null references public.vehicle_makes (id),
  model_id int,
  year_from smallint not null check (year_from between 1950 and 2100),
  year_to smallint not null check (year_to between 1950 and 2100),
  check (year_from <= year_to),
  -- the model (if given) must belong to the make
  foreign key (model_id, make_id) references public.vehicle_models (id, make_id)
);

create index listing_compatibility_listing_idx on public.listing_compatibility (listing_id);
create index listing_compatibility_lookup_idx
  on public.listing_compatibility (make_id, model_id, year_from, year_to);

