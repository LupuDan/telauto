-- 0002: reference data (filled by seed.sql): localities, categories, brands, makes, models.
-- Everyone can read them; only admins can change them.

create table public.localities (
  id smallint primary key,
  name_ro text not null unique,
  name_ru text not null,
  sort_order smallint not null default 100
);

create table public.categories (
  id smallint primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name_ro text not null,
  name_ru text not null,
  sort_order smallint not null default 100
);

create table public.phone_brands (
  id smallint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 40),
  sort_order smallint not null default 100
);

create table public.vehicle_makes (
  id int generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 40)
);

create table public.vehicle_models (
  id int generated by default as identity primary key,
  make_id int not null references public.vehicle_makes (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 60),
  unique (make_id, name),
  -- lets other tables check that a model really belongs to the chosen make
  unique (id, make_id)
);

create index vehicle_models_make_idx on public.vehicle_models (make_id);

-- RLS: read for everyone, write for admins only.
do $$
declare
  t text;
begin
  foreach t in array array['localities', 'categories', 'phone_brands', 'vehicle_makes', 'vehicle_models'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy "%s: everyone can read" on public.%I for select to anon, authenticated using (true)', t, t);
    execute format(
      'create policy "%s: admins can insert" on public.%I for insert to authenticated with check ((select public.is_admin()))', t, t);
    execute format(
      'create policy "%s: admins can update" on public.%I for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))', t, t);
    execute format(
      'create policy "%s: admins can delete" on public.%I for delete to authenticated using ((select public.is_admin()))', t, t);
  end loop;
end;
$$;
